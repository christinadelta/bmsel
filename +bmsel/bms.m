function res = bms(lme, varargin)
%BMS  Random-effects Bayesian model selection (group level).
%
%   res = bmsel.bms(lme)
%   res = bmsel.bms(lme, 'Name', Value, ...)
%
%   Takes a matrix of log model evidence, one row per subject and one
%   column per model, and asks: "how often is each model the best model in
%   the population?" This is the random-effects approach of Stephan et al.
%   (2009), with the Bayesian omnibus risk (BOR) and protected exceedance
%   probabilities of Rigoux et al. (2014). Only base MATLAB is needed.
%
%   INPUT
%     lme   [Nsub x K] log model evidence ln p(y_i | m_k). Any approximation
%           is accepted, for example -BIC/2, -AIC/2, a Laplace or variational
%           free energy, or a cross-validated log-likelihood.
%
%   OPTIONS (name-value pairs)
%     'Nsamp'   number of Dirichlet samples for the exceedance probabilities
%               (default 1e6)
%     'Seed'    seed for the sampling, so results are reproducible
%               (default [] = use the current global random stream)
%     'Alpha0'  prior Dirichlet counts, [1 x K] (default ones(1,K): flat prior)
%     'MaxIter' maximum number of variational iterations (default 10000)
%     'Tol'     convergence tolerance on alpha (default 1e-6)
%
%   OUTPUT  res, a struct with fields
%     alpha   [1 x K] posterior Dirichlet counts
%     exp_r   [1 x K] expected model frequencies, E[r_k | y]
%     xp      [1 x K] exceedance probabilities
%     pxp     [1 x K] protected exceedance probabilities
%     bor     Bayesian omnibus risk, P(H0 | y): the probability that all
%             models are equally frequent in the population
%     g       [Nsub x K] posterior probability that subject i's data were
%             generated by model k
%     F1, F0  log evidence (free energy) of H1 (frequencies differ) and
%             of H0 (all frequencies equal 1/K)
%     iter    number of variational iterations used
%     lme     the input, kept for reference
%
%   HOW TO READ THE OUTPUT
%     exp_r  : the estimated proportion of people best described by each model
%     xp     : the probability that model k is more frequent than every other
%              model. Note that xp of the best model goes to 1 as the sample
%              grows, even when the models are almost equally frequent.
%     bor    : if bor is high (say > 0.25), the data cannot rule out that all
%              models are equally frequent, and xp should not be trusted.
%     pxp    : xp corrected for that risk. This is the number to report.
%
%   THE MODEL (Stephan et al., 2009)
%     Each subject i uses one model m_i. Model labels are drawn from a
%     population with unknown frequencies r = (r_1, ..., r_K):
%
%         r        ~ Dirichlet(alpha0)                 prior on frequencies
%         m_i | r  ~ Categorical(r)                    which model subject i uses
%         y_i | m_i = k  has evidence  p(y_i | k) = exp(lme(i,k))
%
%     The posterior over r is approximated by a Dirichlet(alpha), found with
%     a variational scheme (the maths is in the comments below).
%
%   REFERENCES
%     Stephan, K.E., Penny, W.D., Daunizeau, J., Moran, R.J., Friston, K.J.
%       (2009). Bayesian model selection for group studies. NeuroImage, 46,
%       1004-1017.
%     Rigoux, L., Stephan, K.E., Friston, K.J., Daunizeau, J. (2014).
%       Bayesian model selection for group studies - revisited. NeuroImage,
%       84, 971-985.
%
%   See also bmsel.compare, bmsel.plot.

% ---------------------------------------------------------------- inputs --
p = inputParser;
p.FunctionName = 'bmsel.bms';
addRequired(p, 'lme', @(x) isnumeric(x) && ismatrix(x) && ~isempty(x));
addParameter(p, 'Nsamp',   1e6,  @(x) isscalar(x) && x >= 1);
addParameter(p, 'Seed',    [],   @(x) isempty(x) || (isscalar(x) && x >= 0));
addParameter(p, 'Alpha0',  [],   @(x) isempty(x) || (isnumeric(x) && all(x(:) > 0)));
addParameter(p, 'MaxIter', 1e4,  @(x) isscalar(x) && x >= 1);
addParameter(p, 'Tol',     1e-6, @(x) isscalar(x) && x > 0);
parse(p, lme, varargin{:});
opt = p.Results;

lme = double(lme);
[Nsub, K] = size(lme);
if K < 2
    error('bmsel:bms:oneModel', 'lme must have at least two columns (models).');
end
if any(~isfinite(lme(:)))
    error('bmsel:bms:nonFinite', ...
        'lme contains NaN or Inf. Remove those subjects before calling bms.');
end
if isempty(opt.Alpha0)
    alpha0 = ones(1, K);
else
    alpha0 = double(opt.Alpha0(:))';
    if numel(alpha0) ~= K
        error('bmsel:bms:alpha0Size', 'Alpha0 must have one value per model.');
    end
end

% --------------------------------------------- variational Dirichlet fit --
% We want q(r) = Dirichlet(alpha) and q(m_i = k) = g_ik that best
% approximate the posterior. Iterating the two updates below maximises the
% variational free energy (a lower bound on ln p(y | H1)).
%
%   (1) Expected log frequencies under q(r):
%           E[ln r_k] = psi(alpha_k) - psi(sum_j alpha_j)
%       where psi is the digamma function.
%
%   (2) Posterior model assignment for each subject (responsibilities):
%           g_ik  proportional to  exp( lme(i,k) + E[ln r_k] )
%       normalised so that sum_k g_ik = 1.
%
%   (3) Update of the Dirichlet counts:
%           alpha_k = alpha0_k + sum_i g_ik
%
% Repeat (1)-(3) until alpha stops changing.
alpha = alpha0;
for iter = 1:opt.MaxIter
    alpha_prev = alpha;
    Elogr = psi(alpha) - psi(sum(alpha));          % (1)
    g     = responsibilities(lme, Elogr);          % (2)
    alpha = alpha0 + sum(g, 1);                    % (3)
    if norm(alpha - alpha_prev) < opt.Tol
        break;
    end
end
if iter == opt.MaxIter
    warning('bmsel:bms:noConvergence', ...
        'Variational updates did not converge in %d iterations.', opt.MaxIter);
end

% ------------------------------------------------- expected frequencies --
%   E[r_k | y] = alpha_k / sum_j alpha_j      (mean of a Dirichlet)
exp_r = alpha / sum(alpha);

% ----------------------------------------------- exceedance probabilities --
%   xp_k = P( r_k > r_j  for all j ~= k  |  y )
% There is no closed form for K > 2, so we draw samples from
% Dirichlet(alpha) and count how often each model has the largest r.
if isempty(opt.Seed)
    stream = RandStream.getGlobalStream;
else
    stream = RandStream('mt19937ar', 'Seed', opt.Seed);
end
xp = dirichlet_exceedance(alpha, opt.Nsamp, stream);

% --------------------------------- Bayesian omnibus risk (Rigoux et al.) --
% Compare two hypotheses:
%   H1: model frequencies differ across the population  (the model above)
%   H0: all models are equally frequent, r_k = 1/K for every k
%
% Log evidence of H0. Under H0 each subject's model is a fair draw, so
%   p(y_i | H0) = (1/K) sum_k p(y_i | k)
%   F0 = sum_i ln p(y_i | H0) = sum_i [ logsumexp_k lme(i,k) - ln K ]
F0 = sum(logsumexp_rows(lme) - log(K));

% Log evidence of H1, approximated by the variational free energy at the
% solution found above (see free_energy_H1 below).
F1 = free_energy_H1(lme, alpha, alpha0);

% Posterior probability of H0, with equal prior probability on H0 and H1:
%   BOR = p(H0 | y) = 1 / (1 + exp(F1 - F0))
bor = 1 / (1 + exp(F1 - F0));

% Protected exceedance probability. Under H0 every model is "best" with
% probability 1/K, so we average xp over the two hypotheses:
%   pxp_k = (1 - BOR) * xp_k + BOR / K
pxp = (1 - bor) * xp + bor / K;

% ---------------------------------------------------------------- output --
res = struct('alpha', alpha, 'exp_r', exp_r, 'xp', xp, 'pxp', pxp, ...
             'bor', bor, 'g', g, 'F1', F1, 'F0', F0, 'iter', iter, ...
             'alpha0', alpha0, 'Nsub', Nsub, 'K', K, 'lme', lme);
end


% ======================================================================
% local functions
% ======================================================================
function g = responsibilities(lme, Elogr)
% g_ik = exp(lme_ik + E[ln r_k]) / sum_j exp(lme_ij + E[ln r_j])
% The row maximum is subtracted before exp() to avoid overflow; it cancels
% in the normalisation.
    lu = lme + Elogr;                 % Elogr is 1 x K, expands over rows
    lu = lu - max(lu, [], 2);
    g  = exp(lu);
    g  = g ./ sum(g, 2);
end

function F = free_energy_H1(lme, alpha, alpha0)
% Variational free energy of H1 at the converged solution. This is the same
% quantity as in SPM's spm_BMS_F.m. With q(r) = Dirichlet(alpha) and
% q(m_i = k) = g_ik:
%
%   F = E_q[ ln p(y | m) ]  +  E_q[ ln p(m | r) ]  +  E_q[ ln p(r) ]
%       - E_q[ ln q(m) ]    -  E_q[ ln q(r) ]
%
% where
%   E_q[ln p(y|m)] + E_q[ln p(m|r)] = sum_i sum_k g_ik ( lme_ik + E[ln r_k] )
%   -E_q[ln q(m)]                   = -sum_i sum_k g_ik ln g_ik     (entropy)
%   E_q[ln p(r)]  = ln Gamma(sum alpha0) - sum ln Gamma(alpha0_k)
%                   + sum_k (alpha0_k - 1) E[ln r_k]
%   E_q[ln q(r)]  = ln Gamma(sum alpha)  - sum ln Gamma(alpha_k)
%                   + sum_k (alpha_k - 1) E[ln r_k]
    Elogr = psi(alpha) - psi(sum(alpha));
    g     = responsibilities(lme, Elogr);
    ELJ   = sum(sum(g .* (lme + Elogr)));
    Sqm   = -sum(sum(g .* log(g + eps)));
    Eqlogpr = gammaln(sum(alpha0)) - sum(gammaln(alpha0)) + sum((alpha0 - 1) .* Elogr);
    Eqlogqr = gammaln(sum(alpha))  - sum(gammaln(alpha))  + sum((alpha  - 1) .* Elogr);
    F = ELJ + Sqm + Eqlogpr - Eqlogqr;
end

function y = logsumexp_rows(X)
% ln sum_k exp(X_ik), computed stably by factoring out the row maximum.
    mx = max(X, [], 2);
    y  = mx + log(sum(exp(X - mx), 2));
end
